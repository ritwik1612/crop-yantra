const assert=require('node:assert/strict');
require('../prototype/detection-flow.js');
require('../prototype/architecture.js');
const {architectureMarkup,yieldPanel,imagePanel}=require('../prototype/workspace-flow.js');
const request={district:'Mandya <test>',state:'Karnataka',season:'Kharif',year:2019,areaHa:12,illustrativeYieldTPerHa:4.2,representation:'autoencoder',proposedModel:'mlp'};
let panel=yieldPanel(request,null);
assert.match(panel,/Show prediction flow/);
assert.doesNotMatch(panel,/<details[^>]+open/);
assert.match(panel,/50.4 t/);
assert.match(panel,/50,400 kg/);
assert.match(panel,/Mandya &lt;test&gt;/);
assert.match(panel,/No unique district/);
assert.match(panel,/not executed/);
const ref={TAVG_MEAN:25,PREC_TOTAL:600,GDD_BASE10:2000,CROP_AREA:5000,YIELD:3};
panel=yieldPanel(request,ref,{yieldTPerHa:4.2,scenario:{areaHa:18,productionTonnes:75.6},priceINRPerKg:20,productionKg:50400,grossValueINR:1008000});
assert.match(panel,/25 °C/);
assert.match(panel,/Reference only/);
assert.match(panel,/75.6 t/);
assert.match(panel,/10,08,000/);
const image=imagePanel({image:{mimeType:'image/jpeg',width:480,height:640,bytes:1024},context:{district:'Mandya',state:'Karnataka',season:'Kharif',year:2019}});
assert.match(image,/480 × 640/);
assert.match(image,/Softmax/);
assert.match(image,/not executed/);
assert.match(image,/No logits, scores or label/);
const architecture=architectureMarkup();
for(const name of ['SimpleImputer','StandardScaler','OneHotEncoder','Denoising Autoencoder','MLP','HistGradientBoostingRegressor','EfficientNet-B0'])assert.ok(architecture.includes(name));
console.log('Output audit snapshots, exact arithmetic, missing data, escaping and architecture model names: passed.');
