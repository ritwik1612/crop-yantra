const assert=require('node:assert/strict');
const {summarize}=require('../prototype/outputs.js');
const request={areaHa:12,illustrativeYieldTPerHa:4.2,season:'Kharif',year:2018};
const rows=[{FYEAR:2016,SEASON:'Kharif',YIELD:3},{FYEAR:2018,SEASON:'Kharif',YIELD:4},{FYEAR:2019,SEASON:'Kharif',YIELD:9},{FYEAR:2018,SEASON:'Rabi',YIELD:5}];
let result=summarize(request,rows);
assert.ok(Math.abs(result.productionTonnes-50.4)<1e-10);
assert.ok(Math.abs(result.productionKg-50400)<1e-8);
assert.equal(result.grossValueINR,null);
assert.equal(result.trend.length,2);
assert.equal(result.observedMeanYield,3.5);
assert.equal(result.reference.YIELD,4);
assert.equal(result.modelTrained,false);
result=summarize(request,rows,20,1.5);
assert.ok(Math.abs(result.grossValueINR-1008000)<1e-8);
assert.equal(result.scenario.areaHa,18);
assert.ok(Math.abs(result.scenario.productionTonnes-75.6)<1e-8);
assert.equal(summarize(request,[],0).grossValueINR,0);
assert.equal(summarize(request,[]).reference,null);
assert.equal(summarize(request,[]).observedMeanYield,null);
const live=summarize({...request,areaHa:20,illustrativeYieldTPerHa:12},rows,20,1.5);
assert.equal(live.productionTonnes,240);
assert.equal(live.productionKg,240000);
assert.equal(live.grossValueINR,4800000);
assert.equal(live.scenario.productionTonnes,360);
assert.equal(live.reference.YIELD,4);
assert.equal(summarize({...request,illustrativeYieldTPerHa:0},rows,0).productionKg,0);
const ambiguous=summarize(request,[...rows,{FYEAR:2018,SEASON:'Kharif',YIELD:6}]);
assert.equal(ambiguous.reference,null);
assert.equal(ambiguous.trend.length,1);
assert.deepEqual(ambiguous.ambiguousYears,[2018]);
assert.throws(()=>summarize({...request,areaHa:0},rows));
assert.throws(()=>summarize(request,rows,-1));
assert.throws(()=>summarize(request,rows,null,2));
console.log('Output arithmetic, unavailable references, future-year filtering, ambiguity and validation: passed.');
