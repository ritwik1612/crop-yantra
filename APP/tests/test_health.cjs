const assert=require('node:assert/strict');
const {advisories,validateFile,makeRequest}=require('../prototype/health.js');
const context={districtId:'test',district:'Mandya',state:'Karnataka',season:'Kharif',year:2019,areaHa:12};
let cards=advisories(context,'flowering','warm_humid');
assert.equal(cards.length,3);
assert.ok(cards.every(c=>c.geographicEvidence==='general_rice_handbook_not_district_outbreak'));
assert.ok(cards.some(c=>c.stageMatch&&c.conditionMatch));
assert.ok(advisories(null).every(c=>c.reason.includes('not local outbreak alerts')));
assert.equal(validateFile({size:100,type:'image/png'},Uint8Array.from([137,80,78,71,13,10,26,10])),null);
assert.equal(validateFile({size:100,type:'image/jpeg'},Uint8Array.from([255,216,255])),null);
assert.ok(validateFile({size:100,type:'image/jpeg'},Uint8Array.from([60,115,118,103])));
assert.ok(validateFile({size:11*1024*1024,type:'image/png'},new Uint8Array()));
const request=makeRequest(context,{mimeType:'image/png',bytes:100,width:300,height:300},'unknown','unknown');
assert.equal(request.diseaseName,null);
assert.equal(request.photoTransmitted,false);
assert.equal(request.context.district,'Mandya');
assert.equal(request.imageIncluded,false);
assert.throws(()=>makeRequest(null,{},'unknown','unknown'));
console.log('Advisory provenance, context reuse, file headers, size limits and no fabricated diagnosis: passed.');
