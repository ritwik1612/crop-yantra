const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {renderRows,percentage}=require('../prototype/score-bars.js');
const labels={zero:'Zero',low:'Low',mid:'Middle',high:'Highest',unsafe:'<test>'};
const rows=[{label:'zero',score:0},{label:'low',score:.025},{label:'mid',score:.25},{label:'high',score:.725}];
const html=renderRows(rows,labels);
assert.equal((html.match(/role="meter"/g)||[]).length,4);
for(const width of [0,2.5,25,72.5])assert.ok(html.includes(`style="width:${width}%"`));
assert.equal((html.match(/score-row-leading/g)||[]).length,1);
assert.match(html,/score-row-leading"><span>Highest/);
assert.doesNotMatch(html,/<meter/);
assert.match(renderRows([{label:'unsafe',score:1}],labels),/&lt;test&gt;/);
assert.equal(percentage(.00001),'<0.1%');
assert.equal(percentage(.99999),'>99.9%');
assert.equal(percentage(0),'0%');assert.equal(percentage(1),'100%');
assert.match(renderRows([{label:'zero',score:NaN}],labels),/width:0%/);
assert.doesNotMatch(renderRows([{label:'zero',score:0}],labels),/score-row-leading/);
const desktop=fs.readFileSync(path.join(__dirname,'../desktop/desktop.js'),'utf8');
assert.match(desktop,/HealthScoreBars\.renderRows\(r.scores,labels\)/);
assert.ok(fs.readFileSync(path.join(__dirname,'../prototype/index.html'),'utf8').includes('src="score-bars.js"'));
console.log('Score values, proportional widths, leading class, escaping and renderer integration: passed.');
