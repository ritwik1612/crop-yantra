const assert=require('node:assert/strict');
const {summarize}=require('../prototype/outputs.js');
const charts=require('../prototype/charts.js');
const {illustration}=require('../prototype/health.js');
const {calculation}=require('../prototype/help.js');
const request={illustrativeYieldTPerHa:4.2,areaHa:12,year:2019,season:'Kharif'};
const summary=summarize(request,[{FYEAR:2018,SEASON:'Kharif',YIELD:3.5},{FYEAR:2019,SEASON:'Kharif',YIELD:4}]);
assert.match(charts.comparison(summary),/Recorded district yield/);
assert.match(charts.comparison(summarize(request,[])),/not treated as zero/);
assert.match(charts.scenario(summary,1.2),/60.48/);
assert.notEqual(charts.scenario(summary,.5),charts.scenario(summary,1.5));
assert.match(charts.history(summary),/tabindex="0"/);
assert.equal(charts.history(summarize(request,[])),null);
for(const value of [0,4.2,12]){
 const sample=summarize({...request,illustrativeYieldTPerHa:value},[]);
 assert.doesNotMatch(charts.comparison(sample)+charts.scenario(sample),/NaN|Infinity/);
}
const first=illustration('blast','Kharif','seedling');
assert.notEqual(first,illustration('blast','Rabi','seedling'));
assert.notEqual(first,illustration('blast','Kharif','flowering'));
assert.notEqual(first,illustration('brown_spot','Kharif','seedling'));
assert.match(decodeURIComponent(first),/ILLUSTRATION ONLY/);
assert.doesNotMatch(decodeURIComponent(illustration('blast','<script>','<script>')),/<script>/);
const fs=require('node:fs'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../prototype/index.html'),'utf8');
// Health and outputs are separate routed pages, not an inline pretraining layout.
assert.match(html,/<section id="health" class="page" hidden>/);
assert.match(html,/<section id="results" class="page" hidden>/);
assert.match(html,/href="#results"/);assert.match(html,/href="#health"/);
assert.doesNotMatch(html, /health-teaser|Every harvest starts|Attentive to the leaf/);
assert.match(html,/id="health-season"/);
assert.match(html,/src="charts.js"/);
assert.match(html,/src="help.js"/);
assert.doesNotMatch(html,/id="district-search"|id="search-results"/);
const worked=calculation({areaHa:20,illustrativeYieldTPerHa:5});
assert.match(worked,/INVENTED INPUTS & WEIGHTS/);
assert.match(worked,/84<\/span> tonnes/);
assert.match(worked,/100 tonnes/);
const h1=Math.max(0,.4*.5+.2*.5-.2*(-.5)+.1);
const h2=Math.max(0,-.2*.5+.6*.5+.2*(-.5)+.2);
assert.ok(Math.abs(3.8+.5*h1+.5*h2-4.2)<1e-10);
console.log('Chart states, zero yields, reactive illustration variants and separate health/results routes: passed.');
